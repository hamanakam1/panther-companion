#!/usr/bin/env node
// sync-version.mjs — keep src/version.ts in step with package.json.
//
// package.json is the one place a release version is edited. This script runs
// before tsc on every build so the controller, the MCP server and the surface
// all report the same string without anyone hand-editing three files.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

if (!/^\d+\.\d+\.\d+$/.test(version ?? "")) {
  console.error(`package.json version is not a plain x.y.z release version: ${JSON.stringify(version)}`);
  process.exit(1);
}

const target = join(root, "src", "version.ts");
const next = `/**
 * Generated by scripts/sync-version.mjs from package.json. Do not edit by hand.
 *
 * \`npm run build\` rewrites this file before tsc runs, so package.json is the
 * single source of truth and every reported version (surface header, /api/status
 * and MCP serverInfo) follows one bump. test/mvp.test.ts fails if they diverge.
 */
export const VERSION = ${JSON.stringify(version)};
`;

let current = "";
try { current = readFileSync(target, "utf8"); } catch { /* first run */ }
if (current !== next) {
  writeFileSync(target, next);
  console.log(`version: src/version.ts -> ${version}`);
}
